void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Load .env (holds GOOGLE_MAPS_API_KEY used for reverse geocoding, etc.)
  await dotenv.load(fileName: ".env");

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  FirebaseMessaging.onBackgroundMessage(firebaseMessagingBackgroundHandler);

  // --- Local notifications setup ---
  // Must run before FcmService.showLocalNotification() is ever called,
  // and before background_service.dart's initializeService() creates
  // its own 'location_tracking' channel below.
  final initSettings = InitializationSettings(
    android: AndroidInitializationSettings('@mipmap/ic_launcher'),
  );
  await FlutterLocalNotificationsPlugin().initialize(settings: initSettings);

  const AndroidNotificationChannel alertChannel = AndroidNotificationChannel(
    'alerts',
    'Alerts',
    description: 'Location-off and other admin alerts.',
    importance: Importance.high,
  );
  await FlutterLocalNotificationsPlugin()
      .resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>()
      ?.createNotificationChannel(alertChannel);

  await Supabase.initialize(
    url: 'https://tmoacgbszammuasaxapo.supabase.co',
    anonKey: 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6InRtb2FjZ2JzemFtbXVhc2F4YXBvIiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODY3OTg1MzgsImV4cCI6MjEwMjM3NDUzOH0.NJxYtAyRXPMi8P7H-sClCOpWcBIhqGwz-6TvastkeUw',
  );

  await initializeService();
  SyncService().startListening();

  // CHECK LOGIN STATE
  final prefs = await SharedPreferences.getInstance();
  final userId = prefs.getString('user_id');
  final role = prefs.getString('role');

  Widget initialScreen = const LoginScreen(); // Default to login

  if (role == 'admin') {
    final session = Supabase.instance.client.auth.currentSession;
    if (session != null && userId != null && userId.isNotEmpty) {
      initialScreen = const AdminDashboard();
      FcmService.init(ownerType: 'admin', ownerId: userId).catchError((e) => debugPrint('$e'));
    } else {
      await prefs.clear(); // stale/expired — force re-login
      initialScreen = const LoginScreen();
    }
  } else if (userId != null && userId.isNotEmpty) {
    initialScreen = const TrackerScreen();
    FcmService.init(ownerType: 'user', ownerId: userId).catchError((e) => debugPrint('$e'));
  }

  runApp(MyApp(initialScreen: initialScreen));
}

class MyApp extends StatelessWidget {
  final Widget initialScreen;
  const MyApp({Key? key, required this.initialScreen}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Tracker App',
      theme: ThemeData(primarySwatch: Colors.blue),
      home: initialScreen, // Starts on the correct screen automatically
    );
  }
}